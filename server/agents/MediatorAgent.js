import { GoogleGenerativeAI } from '@google/generative-ai';
import logger from '../services/logger.js';
import sharedAgentMemory from '../services/sharedAgentMemory.js';

/**
 * Mediator Agent
 * Acts as an intelligent bridge between business and customers
 * Handles quotation generation, customer communication, and context management
 */
class MediatorAgent {
  constructor() {
    this.isActive = true;
    if (!process.env.GEMINI_API_KEY || process.env.GEMINI_API_KEY === 'your_gemini_api_key_here') {
      console.warn('GEMINI_API_KEY not configured. MediatorAgent in standby/offline mode.');
      this.isActive = false;
      this.geminiAI = null;
    } else {
      try {
        this.geminiAI = new GoogleGenerativeAI(process.env.GEMINI_API_KEY);
      } catch (err) {
        console.warn('Failed to init Gemini in MediatorAgent:', err.message);
        this.isActive = false;
        this.geminiAI = null;
      }
    }
  }

  /**
   * Process customer message with full context awareness
   */
  async processMessage(sessionId, customerId, businessId, message, conversationHistory = []) {
    try {
      // Get shared context from all agents
      const contextSummary = sharedAgentMemory.generateContextSummary(businessId);
      const serviceCatalog = sharedAgentMemory.getServiceCatalog();
      
      // Build comprehensive prompt with context
      const prompt = this.buildMediatorPrompt(
        message,
        conversationHistory,
        contextSummary,
        serviceCatalog
      );
      
      // Generate AI response using correct API
      const model = this.geminiAI.getGenerativeModel({ model: "gemini-2.0-flash-exp" });
      const result = await model.generateContent(prompt);
      const response = await result.response;
      const aiResponse = response.text();
      
      // Store conversation in shared memory
      sharedAgentMemory.storeConversation(businessId, {
        role: 'customer',
        content: message,
        sessionId,
        customerId
      });
      
      sharedAgentMemory.storeConversation(businessId, {
        role: 'mediator',
        content: aiResponse,
        sessionId
      });
      
      // Store agent interaction
      sharedAgentMemory.storeAgentInteraction(
        businessId,
        'mediator',
        'process_message',
        { sessionId, messageLength: message.length, responseLength: aiResponse.length }
      );
      
      logger.info('Mediator processed message', {
        type: 'agent_mediator',
        sessionId,
        businessId,
        customerId,
        hasContext: !!contextSummary
      });
      
      return {
        response: aiResponse,
        context: contextSummary,
        suggestedActions: this.extractSuggestedActions(aiResponse)
      };
      
    } catch (error) {
      logger.error('Mediator failed to process message', {
        type: 'agent_mediator',
        error: error.message,
        sessionId,
        businessId
      });
      throw error;
    }
  }

  /**
   * Generate quotation for customer
   */
  async generateQuotation(businessId, customerId, requestedServices, customerPreferences = {}) {
    try {
      // Validate services
      const validServices = requestedServices.filter(service => 
        sharedAgentMemory.getServiceDetails(service)
      );
      
      if (validServices.length === 0) {
        throw new Error('No valid services requested');
      }
      
      // Create quotation using shared memory
      const quotation = sharedAgentMemory.createQuotation(
        businessId,
        customerId,
        validServices,
        {
          isReferral: customerPreferences.isReferral || false,
          metadata: {
            generatedBy: 'mediator',
            customerPreferences
          }
        }
      );
      
      // Generate personalized quotation message
      const quotationMessage = await this.generateQuotationMessage(quotation, customerPreferences);
      
      // Store interaction
      sharedAgentMemory.storeAgentInteraction(
        businessId,
        'mediator',
        'generate_quotation',
        {
          quotationId: quotation.id,
          services: validServices,
          total: quotation.pricing.total
        }
      );
      
      logger.info('Quotation generated by mediator', {
        type: 'agent_mediator',
        quotationId: quotation.id,
        businessId,
        customerId,
        services: validServices.length,
        total: quotation.pricing.total
      });
      
      return {
        quotation,
        message: quotationMessage
      };
      
    } catch (error) {
      logger.error('Mediator failed to generate quotation', {
        type: 'agent_mediator',
        error: error.message,
        businessId,
        customerId
      });
      throw error;
    }
  }

  /**
   * Generate personalized quotation message
   */
  async generateQuotationMessage(quotation, customerPreferences) {
    const servicesText = quotation.services
      .map(s => `- ${s.name}: ${s.description}`)
      .join('\n');
    
    const discountsText = quotation.pricing.discounts.length > 0
      ? quotation.pricing.discounts.map(d => `- ${d.description}: -$${d.amount.toFixed(2)}`).join('\n')
      : 'No discounts applied';
    
    const prompt = `Generate a friendly, professional message to present this quotation to a customer:

Services:
${servicesText}

Pricing:
- Subtotal: $${quotation.pricing.subtotal.toFixed(2)}
${discountsText}
- Total: $${quotation.pricing.total.toFixed(2)}

Valid until: ${quotation.validUntil.toLocaleDateString()}

Customer preferences: ${JSON.stringify(customerPreferences)}

Create a warm, engaging message that:
1. Thanks them for their interest
2. Highlights the value of each service
3. Explains any discounts applied
4. Encourages them to accept or ask questions
5. Keeps it concise (3-4 paragraphs max)`;

    const model = this.geminiAI.getGenerativeModel({ model: "gemini-2.0-flash-exp" });
    const result = await model.generateContent(prompt);
    const response = await result.response;
    
    return response.text();
  }

  /**
   * Build comprehensive prompt for mediator
   */
  buildMediatorPrompt(message, conversationHistory, contextSummary, serviceCatalog) {
    const servicesText = serviceCatalog
      .map(s => `- ${s.name} ($${s.basePrice}): ${s.description}`)
      .join('\n');
    
    const historyText = conversationHistory
      .slice(-10)
      .map(msg => `${msg.role}: ${msg.content}`)
      .join('\n');
    
    const contextText = contextSummary 
      ? `Previous interactions: ${contextSummary.summary.totalInteractions}
Recent activity: ${contextSummary.summary.lastActivity}
Quotations sent: ${contextSummary.summary.totalQuotations}`
      : 'No previous context available';
    
    return `You are an AI mediator for BizGrow IT Solutions, helping bridge communication between our business and potential customers.

Your role:
- Understand customer needs and recommend appropriate services
- Generate quotations when requested
- Answer questions about our services professionally
- Build trust and encourage engagement
- Be helpful, friendly, and solution-oriented

Available Services:
${servicesText}

Context:
${contextText}

Conversation History:
${historyText}

Customer Message: ${message}

Respond naturally and helpfully. If the customer is interested in services, you can offer to generate a detailed quotation. Be conversational but professional.`;
  }

  /**
   * Extract suggested actions from AI response
   */
  extractSuggestedActions(response) {
    const actions = [];
    
    // Check for quotation keywords
    if (response.toLowerCase().includes('quotation') || 
        response.toLowerCase().includes('quote') ||
        response.toLowerCase().includes('pricing')) {
      actions.push({
        type: 'generate_quotation',
        label: 'Generate Quotation',
        priority: 'high'
      });
    }
    
    // Check for service recommendations
    const serviceCatalog = sharedAgentMemory.getServiceCatalog();
    serviceCatalog.forEach(service => {
      if (response.toLowerCase().includes(service.name.toLowerCase())) {
        actions.push({
          type: 'recommend_service',
          label: `Recommend ${service.name}`,
          serviceType: service.type,
          priority: 'medium'
        });
      }
    });
    
    // Check for follow-up keywords
    if (response.toLowerCase().includes('schedule') || 
        response.toLowerCase().includes('call') ||
        response.toLowerCase().includes('meeting')) {
      actions.push({
        type: 'schedule_followup',
        label: 'Schedule Follow-up',
        priority: 'medium'
      });
    }
    
    return actions;
  }

  /**
   * Get service recommendations based on customer needs
   */
  async getServiceRecommendations(customerMessage, businessContext = null) {
    try {
      const serviceCatalog = sharedAgentMemory.getServiceCatalog();
      const servicesText = serviceCatalog
        .map(s => `${s.type}: ${s.name} - ${s.description}`)
        .join('\n');
      
      const prompt = `Based on this customer message, recommend the most relevant services:

Customer Message: "${customerMessage}"

Available Services:
${servicesText}

${businessContext ? `Business Context: ${JSON.stringify(businessContext)}` : ''}

Return a JSON array of recommended service types (e.g., ["website", "digital-marketing"]) with brief reasoning.`;

      const model = this.geminiAI.getGenerativeModel({ model: "gemini-2.0-flash-exp" });
      const result = await model.generateContent(prompt);
      const response = await result.response;
      
      const recommendations = JSON.parse(response.text());
      
      return recommendations;
      
    } catch (error) {
      logger.error('Failed to get service recommendations', {
        type: 'agent_mediator',
        error: error.message
      });
      return [];
    }
  }

  /**
   * Handle quotation acceptance
   */
  async handleQuotationAcceptance(quotationId, customerId, acceptanceMessage = '') {
    try {
      const quotation = sharedAgentMemory.getQuotation(quotationId);
      if (!quotation) {
        throw new Error('Quotation not found');
      }
      
      // Update quotation status
      sharedAgentMemory.updateQuotationStatus(quotationId, 'accepted', {
        acceptedBy: customerId,
        acceptanceMessage,
        acceptedAt: new Date()
      });
      
      // Store interaction
      sharedAgentMemory.storeAgentInteraction(
        quotation.businessId,
        'mediator',
        'quotation_accepted',
        {
          quotationId,
          customerId,
          total: quotation.pricing.total
        }
      );
      
      logger.info('Quotation accepted', {
        type: 'agent_mediator',
        quotationId,
        customerId,
        businessId: quotation.businessId,
        total: quotation.pricing.total
      });
      
      return {
        success: true,
        quotation,
        nextSteps: 'Our team will contact you within 24 hours to discuss project details and timeline.'
      };
      
    } catch (error) {
      logger.error('Failed to handle quotation acceptance', {
        type: 'agent_mediator',
        error: error.message,
        quotationId
      });
      throw error;
    }
  }

  /**
   * Handle quotation rejection
   */
  async handleQuotationRejection(quotationId, customerId, rejectionReason = '') {
    try {
      const quotation = sharedAgentMemory.getQuotation(quotationId);
      if (!quotation) {
        throw new Error('Quotation not found');
      }
      
      // Update quotation status
      sharedAgentMemory.updateQuotationStatus(quotationId, 'rejected', {
        rejectedBy: customerId,
        rejectionReason,
        rejectedAt: new Date()
      });
      
      // Store interaction
      sharedAgentMemory.storeAgentInteraction(
        quotation.businessId,
        'mediator',
        'quotation_rejected',
        {
          quotationId,
          customerId,
          reason: rejectionReason
        }
      );
      
      logger.info('Quotation rejected', {
        type: 'agent_mediator',
        quotationId,
        customerId,
        businessId: quotation.businessId,
        reason: rejectionReason
      });
      
      return {
        success: true,
        message: 'Thank you for your feedback. Would you like us to adjust the proposal or discuss alternative options?'
      };
      
    } catch (error) {
      logger.error('Failed to handle quotation rejection', {
        type: 'agent_mediator',
        error: error.message,
        quotationId
      });
      throw error;
    }
  }

  /**
   * Get agent status
   */
  getStatus() {
    const stats = sharedAgentMemory.getStatistics();
    
    return {
      isActive: this.isActive,
      sharedMemory: {
        businessContexts: stats.businessContexts,
        conversations: stats.conversationHistories,
        quotations: stats.quotations
      }
    };
  }
}

// Create singleton instance
const mediatorAgent = new MediatorAgent();

export default mediatorAgent;
export { MediatorAgent };
